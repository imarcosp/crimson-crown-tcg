CREATE OR REPLACE FUNCTION public.approve_buylist_transaction(buylist_id_input uuid, amount_to_credit numeric)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
BEGIN
  -- A. Actualizar estado de la orden
  UPDATE buylist_orders
  SET status = 'completed'
  WHERE id = buylist_id_input;

  -- B. Sumar créditos al usuario
  UPDATE profiles
  SET credits = credits + amount_to_credit
  WHERE id = (SELECT user_id FROM buylist_orders WHERE id = buylist_id_input);

  -- C. Registrar transacción (CORREGIDO: usa 'type' y 'description')
  INSERT INTO credit_transactions (
    user_id, 
    amount, 
    type, 
    description, 
    reference_id
  )
  VALUES (
    (SELECT user_id FROM buylist_orders WHERE id = buylist_id_input),
    amount_to_credit,
    'buylist',  -- Valor para la columna 'type'
    'Venta aprobada (Buylist)', -- Valor para la columna 'description'
    buylist_id_input
  );
END;
$function$
;

CREATE OR REPLACE FUNCTION public.assign_import_order_number()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
declare
  n int;
  candidate text;
begin
  perform pg_advisory_lock(8712346);

  -- Si viene número y ya existe, lo reemplazamos
  if new.order_number is not null then
    if exists (select 1 from public.import_orders where order_number = new.order_number) then
      n := nextval('public.import_order_seq');
      candidate := 'IMP-' || lpad(n::text, 4, '0');
      new.order_number := candidate;
    end if;
  else
    -- Si no viene, asignamos el siguiente de la secuencia
    n := nextval('public.import_order_seq');
    candidate := 'IMP-' || lpad(n::text, 4, '0');
    new.order_number := candidate;
  end if;

  perform pg_advisory_unlock(8712346);
  return new;

exception when others then
  perform pg_advisory_unlock(8712346);
  raise;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.decrement_stock(qty integer, row_id uuid)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
begin
  update products 
