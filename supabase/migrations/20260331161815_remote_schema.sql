CREATE OR REPLACE FUNCTION public.transfer_credits(recipient_email text, amount numeric, note text DEFAULT ''::text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
declare
  v_sender_id uuid := auth.uid();
  v_sender_email text;
  v_recipient_id uuid;
  v_sender_balance numeric;
  v_tracking_id text := gen_random_uuid(); -- Generamos un ID único para este par de movimientos
begin
  -- Validaciones
  if amount <= 0 then
    raise exception 'El monto debe ser mayor a 0.';
  end if;

  -- Obtener email del remitente para mostrarlo al receptor
  select email into v_sender_email from profiles where id = v_sender_id;

  -- Buscar destinatario
  select id into v_recipient_id from profiles where email = recipient_email;
  
  if v_recipient_id is null then
    raise exception 'El usuario destinatario no existe.';
  end if;

  if v_recipient_id = v_sender_id then
    raise exception 'No puedes transferirte a ti mismo.';
  end if;

  -- Verificar saldo
  select credits into v_sender_balance from profiles where id = v_sender_id;
  
  if v_sender_balance < amount then
    raise exception 'Saldo insuficiente.';
  end if;

  -- EJECUTAR TRANSFERENCIA
  update profiles set credits = credits - amount where id = v_sender_id;
  update profiles set credits = coalesce(credits, 0) + amount where id = v_recipient_id;

  -- REGISTRAR HISTORIAL (Con Rastreo, Nota y Remitente)
  
  -- Log para el Emisor
  insert into credit_transactions (user_id, amount, type, transaction_desc, ref_id, created_at)
  values (
    v_sender_id, 
    -amount, 
    'transfer_sent', 
    'Enviado a ' || recipient_email || (case when note <> '' then ' - Nota: ' || note else '' end), 
    v_tracking_id, 
    now()
  );

  -- Log para el Receptor (Ahora ve quién se lo mandó)
  insert into credit_transactions (user_id, amount, type, transaction_desc, ref_id, created_at)
  values (
    v_recipient_id, 
    amount, 
    'transfer_received', 
    'Recibido de ' || v_sender_email || (case when note <> '' then ' - Nota: ' || note else '' end), 
    v_tracking_id, 
    now()
  );

end;
$function$
;

