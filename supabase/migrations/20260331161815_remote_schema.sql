CREATE OR REPLACE FUNCTION public.merge_duplicate_products(batch_size integer DEFAULT 100)
 RETURNS text
 LANGUAGE plpgsql
AS $function$
DECLARE
    r RECORD;
    original_id UUID;
    duplicate_id UUID;
    processed_count INT := 0;
BEGIN
    FOR r IN 
        SELECT name, set_name, finish, condition, language, count(*) 
        FROM products 
        WHERE tcg = 'Magic'
          AND name NOT LIKE '%(ARCHIVADO)%' -- Ignoramos los que ya nos rendimos
        GROUP BY name, set_name, finish, condition, language
        HAVING count(*) > 1
        LIMIT batch_size
    LOOP
        -- 1. Identificar Original (El que tiene stock o es más viejo)
        SELECT id INTO original_id
        FROM products
        WHERE name = r.name AND set_name = r.set_name AND finish = r.finish 
          AND condition = r.condition AND language = r.language
          AND name NOT LIKE '%(ARCHIVADO)%'
        ORDER BY stock DESC, created_at ASC
        LIMIT 1;

        -- 2. Identificar Duplicados para eliminar
        FOR duplicate_id IN 
            SELECT id FROM products 
            WHERE name = r.name AND set_name = r.set_name AND finish = r.finish 
              AND condition = r.condition AND language = r.language
              AND id != original_id
        LOOP
            -- Mover Carritos (Sumar si existe, mover si no)
            UPDATE cart_items c1
            SET quantity = c1.quantity + c2.quantity
            FROM cart_items c2
            WHERE c1.user_id = c2.user_id AND c1.product_id = original_id::text AND c2.product_id = duplicate_id::text;
            
            DELETE FROM cart_items WHERE product_id = duplicate_id::text; -- Borrar conflicto
            UPDATE cart_items SET product_id = original_id::text WHERE product_id = duplicate_id::text; -- Mover resto

            -- Mover Wishlists
            DELETE FROM wishlists WHERE product_id = duplicate_id AND user_id IN (SELECT user_id FROM wishlists WHERE product_id = original_id);
            UPDATE wishlists SET product_id = original_id WHERE product_id = duplicate_id;

            -- Mover Saved Items
            BEGIN
                DELETE FROM saved_items WHERE product_id = duplicate_id::text AND user_id IN (SELECT user_id FROM saved_items WHERE product_id = original_id::text);
                UPDATE saved_items SET product_id = original_id::text WHERE product_id = duplicate_id::text;
            EXCEPTION WHEN OTHERS THEN NULL; END;

            -- 3. INTENTO FINAL DE BORRADO O ARCHIVADO
            BEGIN
                DELETE FROM products WHERE id = duplicate_id;
            EXCEPTION WHEN foreign_key_violation THEN
                -- SI FALLA EL BORRADO, LO RENOMBRAMOS PARA ROMPER EL BUCLE
                UPDATE products 
                SET 
                    stock = 0, 
                    is_manual_price = true,
                    name = name || ' (ARCHIVADO)', 
                    scryfall_id = NULL 
                WHERE id = duplicate_id;
            END;
        END LOOP;
        
        processed_count := processed_count + 1;
    END LOOP;

    RETURN 'Se procesaron ' || processed_count || ' grupos restantes.';
END;
$function$
;

