CREATE OR REPLACE FUNCTION public.generate_next_import_order_number()
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
declare
  n int := 0;
  candidate text;
begin
  perform pg_advisory_lock(8712345);

  select coalesce(max((regexp_replace(order_number, '^IMP-', ''))::int), 0)
    into n
  from public.import_orders
  where order_number ~ '^IMP-\d{4}$';

  loop
    n := n + 1;
    candidate := 'IMP-' || lpad(n::text, 4, '0');

    exit when not exists (
      select 1 from public.import_orders where order_number = candidate
    );
  end loop;

  perform pg_advisory_unlock(8712345);
  return candidate;

exception when others then
  perform pg_advisory_unlock(8712345);
  raise;
end;
$function$
